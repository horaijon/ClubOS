test('withdrawal opens a funding recovery plan and approval changes persisted allocations', async ({page})=>{
  await page.request.post('/api/auth/demo')
  await page.goto('/#dashboard')
  await page.getByRole('button',{name:'Simulate disruption'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'VectorForge withdraws ₹20,000'}).click()
  await expect(page.getByRole('region',{name:'Live orchestration trace'}).getByText('Workflow complete.')).toBeVisible()
  await page.getByRole('navigation').getByRole('link',{name:'Approvals & Risks'}).click()
  await expect(page.getByRole('heading',{name:'Recover the funding shortfall'})).toBeVisible()
  await expect(page.getByRole('table',{name:'Projected budget impact'})).toContainText('₹15,000')
  const events=await (await page.request.get('/api/events')).json()
  const snapshot=async ()=>(await page.request.get('/api/events/'+events[0].id)).json()
  const withdrawn=await snapshot()
  expect(withdrawn.metrics.shortfall).toBe(1500000)
  const approve = page.locator('article').filter({has:page.getByRole('heading',{name:'Recover the funding shortfall'})}).getByRole('button',{name:'Approve plan',exact:true})
  const dialog = page.getByRole('dialog')
  await approve.click()
  await expect(dialog.getByRole('button',{name:'Cancel',exact:true})).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(approve).toBeFocused()
  await approve.click()
  await dialog.getByRole('button',{name:'Approve and apply',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Recover the funding shortfall'})).toBeVisible()
  await expect.poll(async ()=>(await snapshot()).metrics.planned).toBeLessThan(6000000)
  await page.reload()
  await expect(page.getByRole('heading',{name:'Approvals & Risks'})).toBeVisible()
  expect((await snapshot()).metrics.projected_funding).toBe(4500000)
  expect((await snapshot()).metrics.planned).toBeLessThan(6000000)
})


test('event trends filter chart history and export CSV', async ({page})=>{
  await page.request.post('/api/auth/demo')
  await page.goto('/#dashboard')
  await expect(page.getByRole('heading',{name:'Projected funding'})).toBeVisible()
  await page.getByRole('button',{name:'Event trends'}).click()
  await expect(page.getByRole('heading',{name:'Tasks by status'})).toBeVisible()
  const trends=page.locator('.dash-trends')
  await trends.getByRole('button',{name:'30 days',exact:true}).click()
  await expect(trends.getByRole('button',{name:'30 days',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('region',{name:/Automation activity over 30 days/})).toBeVisible()
  const downloading=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export CSV'}).click()
  const report=await downloading
  expect(report.suggestedFilename()).toBe('clubos-event-trends.csv')
  let csv=''
  for await(const chunk of await report.createReadStream())csv+=chunk.toString()
  expect(csv.split('\n')).toHaveLength(31)
  expect(csv).toContain('date,new_registrations,total_registrations,completed_runs,approval_runs')
  await page.getByRole('navigation').getByRole('link',{name:'Tasks & Ops'}).click()
  await expect(page.getByRole('heading',{name:'Event work board'})).toBeVisible()
})


